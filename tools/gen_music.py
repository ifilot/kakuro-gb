#!/usr/bin/env python3
"""Generate src/music.h and src/music.c: the background music, written
below as notes, for sound.c.

Two voices: the tune on channel 2 (a square wave that fades) and the bass
on channel 3 (a triangle wave). A note is its name and octave ("C4", "F#3",
"Bb2", "R" for a rest) and its length in sixteenths. The tune is in C
major, 32 bars (A B A B'), and loops.

Per note the data hold the channel's frequency value (little endian, 0 for
a rest) and the length in ticks of the sound timer (TIMER_HZ in clock.h); a
length of 0 ends the voice, which then starts again. A bass note is cut two
ticks short, so repeated notes are heard as such.

  python3 tools/gen_music.py
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src/music.h"
TIMER_HZ = 64                     # clock.h
SIXTEENTH = 9                     # ticks: a quarter note is 36/64 s, 107 beats a minute
BASS_GAP = 2

# --- the tune -----------------------------------------------------------------

A = [
    "E4 4  G4 4  C5 4  B4 2  G4 2",      # C
    "A4 6  G4 2  E4 8",                  # Am
    "F4 4  A4 4  C5 4  A4 4",            # F
    "G4 12 R 4",                         # G
    "E4 4  G4 4  C5 4  D5 2  E5 2",      # C
    "C5 6  B4 2  A4 8",                  # Am
    "F4 4  A4 4  G4 4  B4 4",            # Dm G
    "C5 12 R 4",                         # C
]
B = [
    "A4 4  C5 4  F5 6  E5 2",            # F
    "D5 6  C5 2  B4 8",                  # G
    "G4 4  B4 4  E5 6  D5 2",            # Em
    "C5 6  B4 2  A4 8",                  # Am
    "F4 4  A4 4  C5 4  F5 4",            # F
    "E5 4  D5 4  B4 4  G4 4",            # G
    "A4 4  C5 4  A4 4  F4 4",            # Am F
    "G4 8  F4 4  D4 4",                  # G, back to C
]
B_END = B[:6] + [
    "F4 4  A4 4  B4 4  D5 4",            # Dm G
    "C5 12 R 4",                         # C, and from the top
]

# The bass walks root, fifth, octave, fifth in quarters; a bar of two
# chords has root and fifth of each.
CHORD = {
    "C": "C3 4  G3 4  C4 4  G3 4",
    "Am": "A2 4  E3 4  A3 4  E3 4",
    "F": "F2 4  C3 4  F3 4  C3 4",
    "G": "G2 4  D3 4  G3 4  D3 4",
    "Em": "E2 4  B2 4  E3 4  B2 4",
    "Dm G": "D3 4  A3 4  G2 4  D3 4",
    "Am F": "A2 4  E3 4  F2 4  C3 4",
}
A_CHORDS = ["C", "Am", "F", "G", "C", "Am", "Dm G", "C"]
B_CHORDS = ["F", "G", "Em", "Am", "F", "G", "Am F", "G"]
B_END_CHORDS = B_CHORDS[:6] + ["Dm G", "C"]

TUNE = A + B + A + B_END
BASS = [CHORD[c] for c in A_CHORDS + B_CHORDS + A_CHORDS + B_END_CHORDS]

# --- encoding -----------------------------------------------------------------

NAMES = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}


def hz(note: str) -> float:
    semitone = NAMES[note[0]] + note[1:-1].count("#") - note[1:-1].count("b")
    midi = 12 * (int(note[-1]) + 1) + semitone
    return 440.0 * 2 ** ((midi - 69) / 12)


def notes(bars: list[str]) -> list[tuple[str, int]]:
    out = []
    for k, bar in enumerate(bars):
        words = bar.split()
        pairs = [(words[i], int(words[i + 1])) for i in range(0, len(words), 2)]
        assert sum(n for _, n in pairs) == 16, f"bar {k + 1}: {bar!r} is not 16 sixteenths"
        out += pairs
    return out


def encode(pairs: list[tuple[str, int]], clock: int, gap: int = 0) -> bytes:
    """clock: the channel's 131072 (square) or 65536 (wave)."""
    data = bytearray()

    def put(x: int, ticks: int) -> None:
        while ticks > 255:
            data.extend((x & 0xFF, x >> 8, 255))
            ticks -= 255
        data.extend((x & 0xFF, x >> 8, ticks))

    for name, length in pairs:
        ticks = length * SIXTEENTH
        if name == "R":
            put(0, ticks)
            continue
        x = round(2048 - clock / hz(name))
        assert 0 < x < 2048, name
        put(x, ticks - gap)
        if gap:
            put(0, gap)
    data.extend((0, 0, 0))
    return bytes(data)


def c_array(name: str, data: bytes) -> str:
    items = [f"0x{b:02X}" for b in data]
    body = ",\n".join("    " + ", ".join(items[i:i + 12]) for i in range(0, len(items), 12))
    return f"const unsigned char {name}[{len(data)}] = {{\n{body}\n}};\n"


def main() -> int:
    lead = encode(notes(TUNE), 131072)
    bass = encode(notes(BASS), 65536, BASS_GAP)
    OUTPUT.write_text("\n".join([
        "/* Generated by tools/gen_music.py -- do not edit. */",
        "#ifndef MUSIC_H", "#define MUSIC_H", "",
        "/* A voice: per note the channel's frequency value (little endian, 0 a rest)",
        f" * and its length in ticks ({TIMER_HZ} a second); a length of 0 ends it. */",
        "extern const unsigned char music_lead[], music_bass[];", "", "#endif", ""]))
    OUTPUT.with_suffix(".c").write_text("\n".join([
        "/* Generated by tools/gen_music.py -- do not edit. */",
        '#include "music.h"', "",
        c_array("music_lead", lead), c_array("music_bass", bass)]))
    seconds = len(TUNE) * 16 * SIXTEENTH / TIMER_HZ
    print(f"wrote src/music.h and .c: {len(TUNE)} bars, {seconds:.0f} s, {len(lead) + len(bass)} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
